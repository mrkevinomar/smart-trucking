/// Keyed copy. Spanish is the default; the EN table has the same keys.
/// Strings with `{x}` placeholders are filled with [Strings.f].
class Strings {
  const Strings(this.locale);

  final AppLocale locale;

  static Strings of(BuildContext context) =>
      Localizations.of<Strings>(context, Strings) ?? const Strings(AppLocale.es);

  Map<String, String> get _table => locale == AppLocale.es ? es : en;

  /// Translate a key. Unknown keys return the key itself so a missing string is
  /// visible on screen instead of crashing the prototype.
  String call(String key) => _table[key] ?? key;

  /// Translate with placeholders: `f('net_payout', {'x': '405', 'rate': '10'})`.
  String f(String key, Map<String, String> args) {
    var s = call(key);
    args.forEach((k, v) => s = s.replaceAll('{$k}', v));
    return s;
  }

  // ---- Booking / listing state labels (4.6 second table) -----------------

  String bookingLabel(BookingStatus s, {UserRole? viewer}) {
    if (s == BookingStatus.offered) {
      // "Oferta enviada / Oferta recibida" depends on who looks at it.
      return viewer == UserRole.shipper
          ? call('bs_offered_sent')
          : call('bs_offered_received');
    }
    return call('bs_${s.name}');
  }

  String bookingNotification(BookingStatus s) => call('bn_${s.name}');

  String listingLabel(ListingStatus s) => call('ls_${s.name}');

