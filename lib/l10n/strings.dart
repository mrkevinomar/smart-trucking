/// Delegate so `Localizations.of<Strings>` works and the whole tree rebuilds
/// when the locale changes.
class StringsDelegate extends LocalizationsDelegate<Strings> {
  const StringsDelegate(this.appLocale);
  final AppLocale appLocale;

  @override
  bool isSupported(Locale locale) => true;

  @override
  Future<Strings> load(Locale locale) async => Strings(appLocale);

  @override
  bool shouldReload(StringsDelegate old) => old.appLocale != appLocale;
}

/// Convenience: `context.t('key')`.
extension StringsContext on BuildContext {
  Strings get t => Strings.of(this);
}

/// Label for a [VerificationState] (S05).
String verificationLabel(Strings t, VerificationState s) {
  switch (s) {
    case VerificationState.pending:
      return t('s05_pending');
    case VerificationState.approved:
      return t('s05_approved');
    case VerificationState.rejected:
      return t('s05_rejected');
    case VerificationState.exhausted:
      return t('s05_exhausted');
  }
}
